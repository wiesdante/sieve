"""Shared, editable rules for the email junk filter.

The rules are stored in ``%APPDATA%\\Sieve\\data\\email_filter_rules.json`` and
used by every tool that cleans email addresses.
"""

from __future__ import annotations

import logging

from PySide6.QtWidgets import (
    QCheckBox,
    QDialog,
    QHBoxLayout,
    QMessageBox,
    QPlainTextEdit,
    QPushButton,
    QTabWidget,
    QVBoxLayout,
    QWidget,
)

from sieve.core.email_filter import EmailFilter, EmailRules
from sieve.storage import JsonDocument
from sieve.ui.widgets import muted_label, primary_button

log = logging.getLogger(__name__)

DOCUMENT = "email_filter_rules"

LIST_TABS = (
    ("blocked_domains", "Domains", "Addresses at these domains (and their subdomains) are removed."),
    ("domain_keywords", "Domain words", "Addresses whose domain contains any of these are removed."),
    ("blocked_usernames", "Usernames", "Addresses whose part before @ is exactly one of these are removed."),
    ("username_prefixes", "Username starts", "Addresses whose part before @ starts with one of these are removed."),
    ("blocked_emails", "Addresses", "These exact addresses are removed."),
)


def load_rules() -> EmailRules:
    data = JsonDocument(DOCUMENT).load()
    return EmailRules.from_dict(data) if data else EmailRules()


def save_rules(rules: EmailRules) -> None:
    JsonDocument(DOCUMENT).save(rules.to_dict())


def load_filter() -> EmailFilter:
    return EmailFilter(load_rules())


class EmailRulesDialog(QDialog):
    def __init__(self, parent: QWidget | None = None) -> None:
        super().__init__(parent)
        self.setWindowTitle("Email filter rules")
        self.resize(620, 520)
        layout = QVBoxLayout(self)
        layout.setSpacing(10)
        layout.addWidget(muted_label(
            "These rules decide which addresses count as junk. One entry per line; letter case "
            "does not matter. They are shared by every tool and saved automatically when you "
            "click Save."
        ))

        self._tabs = QTabWidget()
        self._editors: dict[str, QPlainTextEdit] = {}
        for name, title, hint in LIST_TABS:
            page = QWidget()
            page_layout = QVBoxLayout(page)
            page_layout.setContentsMargins(10, 10, 10, 10)
            page_layout.addWidget(muted_label(hint))
            editor = QPlainTextEdit()
            editor.setObjectName("Editor")
            page_layout.addWidget(editor, 1)
            self._editors[name] = editor
            self._tabs.addTab(page, title)
        layout.addWidget(self._tabs, 1)

        self._tokens = QCheckBox("Remove addresses that look like tokens or hashes")
        self._tokens.setToolTip(
            "For example 5e9d8f7a3b2c1d0e@... or very long usernames generated by tracking tools."
        )
        self._placeholders = QCheckBox("Remove placeholder addresses (example.net, test.org, yourname@...)")
        layout.addWidget(self._tokens)
        layout.addWidget(self._placeholders)

        buttons = QHBoxLayout()
        reset = QPushButton("Reset to defaults")
        reset.clicked.connect(self._reset)
        cancel = QPushButton("Cancel")
        cancel.clicked.connect(self.reject)
        save = primary_button("Save")
        save.clicked.connect(self._save)
        buttons.addWidget(reset)
        buttons.addStretch(1)
        buttons.addWidget(cancel)
        buttons.addWidget(save)
        layout.addLayout(buttons)

        self._show(load_rules())

    def _show(self, rules: EmailRules) -> None:
        for name, editor in self._editors.items():
            editor.setPlainText("\n".join(getattr(rules, name)))
        self._tokens.setChecked(rules.block_tokens)
        self._placeholders.setChecked(rules.block_placeholders)

    def _reset(self) -> None:
        answer = QMessageBox.question(
            self, "Reset rules", "Replace all lists with the built-in defaults?"
        )
        if answer == QMessageBox.StandardButton.Yes:
            self._show(EmailRules())

    def _save(self) -> None:
        data = {name: editor.toPlainText() for name, editor in self._editors.items()}
        data["block_tokens"] = self._tokens.isChecked()
        data["block_placeholders"] = self._placeholders.isChecked()
        try:
            save_rules(EmailRules.from_dict(data))
        except OSError as exc:
            log.exception("Could not save email rules")
            QMessageBox.critical(self, "Email filter rules", f"The rules could not be saved:\n{exc}")
            return
        self.accept()
